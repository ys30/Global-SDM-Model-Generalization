# Factorial MaxEnt sensitivity: identical taxa for all 16 configurations.
dir.create("results/maxnet_summary",recursive=TRUE,showWarnings=FALSE)
regions<-c("AWT","CAN","NSW","NZ","SA","SWI")
a<-do.call(rbind,lapply(regions,function(r){d<-read.csv(file.path("inputs",paste0("maxnet-sensitivity-",r),"metrics.csv"));stopifnot(all(d$region==r));d}))
keys<-c("region","group","species")
stopifnot(!anyDuplicated(a[c(keys,"model")]))
f<-c("l","lq","lqh","lqhpt");regs<-c(.5,1,2,4)
grid<-expand.grid(feature=f,regmult=regs,stringsAsFactors=FALSE)
grid$model<-paste0("maxnet_",grid$feature,"_r",grid$regmult)
stopifnot(setequal(unique(a$model),grid$model))
a$success<-as.logical(a$success)
a$auc[!a$success]<-NA_real_
b<-reshape(a[c(keys,"model","auc")],idvar=keys,timevar="model",direction="wide")
cols<-paste0("auc.",grid$model)
b<-b[complete.cases(b[cols]),];stopifnot(nrow(b)==194)
rr<-aggregate(b[cols],b["region"],mean)
global<-data.frame(grid,auc=as.numeric(colMeans(rr[cols])))
print(table(b$region));print(global)
success<-aggregate(as.integer(a$success),a[c("region","model")],function(x)c(n=length(x),success=sum(x),rate=mean(x)))
print(success)
set.seed(20261128)
summ<-function(v,label){
 z<-split(v,b$region);m<-vapply(z,mean,0.0)
 bs<-sapply(z,function(x)replicate(4000,mean(sample(x,length(x),replace=TRUE))))
 q<-quantile(rowMeans(bs),c(.025,.975))
 loo<-sapply(names(m),function(r)mean(m[names(m)!=r]))
 data.frame(contrast=label,n=length(v),mean=mean(m),lower=q[1],upper=q[2],loo_min=min(loo),loo_max=max(loo))
}
v<-function(f,r)b[[paste0("auc.maxnet_",f,"_r",r)]]
out<-list()
for(r in regs)for(i in 2:4)out[[length(out)+1]]<-summ(v(f[i],r)-v(f[i-1],r),paste0(f[i],"_minus_",f[i-1],"_r",r))
for(g in f)for(r in c(.5,2,4))out[[length(out)+1]]<-summ(v(g,r)-v(g,1),paste0(g,"_r",r,"_minus_r1"))
for(r in c(.5,2,4))out[[length(out)+1]]<-summ((v("lqhpt",r)-v("lqh",r))-(v("lqhpt",1)-v("lqh",1)),paste0("complexity_interaction_r",r))
ci<-do.call(rbind,out);print(ci)
write.csv(global,"results/maxnet_summary/global.csv",row.names=FALSE)
write.csv(rr,"results/maxnet_summary/region.csv",row.names=FALSE)
write.csv(ci,"results/maxnet_summary/contrasts.csv",row.names=FALSE)
write.csv(b,"results/maxnet_summary/matched.csv",row.names=FALSE)
write.csv(success,"results/maxnet_summary/success.csv",row.names=FALSE)
