# Paired PO benchmark inference on common nine-model species.
dir.create("results/po_summary",recursive=TRUE,showWarnings=FALSE)
regions<-c("AWT","CAN","NSW","NZ","SA","SWI")
a<-do.call(rbind,lapply(regions,function(r){d<-read.csv(file.path("inputs/new",paste0("po-revised-",r),"matched_species.csv"));stopifnot(all(d$region==r));d}))
old<-read.csv("inputs/old/matched_species.csv")
keys<-c("region","group","species");stopifnot(!anyDuplicated(a[keys]),!anyDuplicated(old[keys]))
cols<-grep("^auc\\.",names(a),value=TRUE);stopifnot(length(cols)==9)
j<-merge(a,old,by=keys,suffixes=c("_new","_old"))
print(table(a$region));print(table(j$region))
rr<-aggregate(a[cols],a["region"],mean);print(rr);print(colMeans(rr[cols]))
set.seed(20261127)
summ<-function(v,r,label){
 z<-split(v,r);stopifnot(length(z)==6,all(is.finite(v)))
 bs<-sapply(z,function(x)replicate(4000,mean(sample(x,length(x),replace=TRUE))))
 q<-quantile(rowMeans(bs),c(.025,.975));m<-vapply(z,mean,0.0)
 data.frame(contrast=label,n=length(v),mean=mean(m),lower=q[1],upper=q[2],loo_min=min(sapply(names(m),function(r)mean(m[names(m)!=r]))),loo_max=max(sapply(names(m),function(r)mean(m[names(m)!=r]))))
}
pairs<-list(c("maxnet_lq","maxnet_l"),c("maxnet_lqh","maxnet_lq"),c("maxnet_lqhpt","maxnet_lqh"),c("ridge_l","glm_l"),c("ridge_q","glm_q"),c("ridge_q","maxnet_lqh"),c("xgb_shallow","maxnet_lqh"))
out<-lapply(pairs,function(p)summ(a[[paste0("auc.",p[1])]]-a[[paste0("auc.",p[2])]],a$region,paste(p,collapse="_minus_")))
for(m in c("ridge_l","ridge_q"))out[[length(out)+1]]<-summ(j[[paste0("auc.",m,"_new")]]-j[[paste0("auc.",m,"_old")]],j$region,paste0(m,"_solver_repair"))
z<-do.call(rbind,out);print(z)
write.csv(rr,"results/po_summary/region.csv",row.names=FALSE)
write.csv(a,"results/po_summary/species.csv",row.names=FALSE)
write.csv(j,"results/po_summary/replay.csv",row.names=FALSE)
write.csv(z,"results/po_summary/contrasts.csv",row.names=FALSE)
